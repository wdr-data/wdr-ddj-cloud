"""One-off script: generate gemeinden_nrw.py from the Destatis Gemeindeverzeichnis.

Run from the repo root (pass a newer quarter's URL to update):
    uv run ddj_cloud/data/generate_gemeinden_nrw.py [URL]
    uv run ruff format ddj_cloud/data/gemeinden_nrw.py
"""

# /// script
# requires-python = ">=3.12"
# dependencies = ["openpyxl"]
# ///

import io
import sys
import urllib.request
from pathlib import Path

import openpyxl

DEFAULT_URL = "https://www.destatis.de/DE/Themen/Laender-Regionen/Regionales/Gemeindeverzeichnis/Administrativ/Archiv/GVAuszugQ/AuszugGV3QAktuell.xlsx?__blob=publicationFile"
OUT_PATH = Path(__file__).parent / "gemeinden_nrw.py"

SATZART_KREIS = "40"
SATZART_GEMEINDE = "60"
TEXTKENNZEICHEN_KREISFREIE_STADT = "41"


def clean_name(name: str) -> str:
    """Strip epithets like ", Stadt" or ", Hansestadt"."""
    return name.split(",", 1)[0].strip()


def main():
    url = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_URL
    with urllib.request.urlopen(url) as response:
        workbook = openpyxl.load_workbook(io.BytesIO(response.read()), read_only=True)
    sheet = workbook.worksheets[1]
    title = sheet["A1"].value

    kreise = {}
    gemeinden = {}
    for satzart, textkennzeichen, land, rb, kreis, _vb, gem, name, *_ in sheet.iter_rows(
        min_row=7, values_only=True
    ):
        if land != "05":
            continue
        if satzart == SATZART_KREIS:
            kreise[land + rb + kreis] = (
                clean_name(name),
                textkennzeichen == TEXTKENNZEICHEN_KREISFREIE_STADT,
            )
        elif satzart == SATZART_GEMEINDE:
            gemeinden[land + rb + kreis + gem] = clean_name(name)

    lines = [
        '"""NRW municipalities by 8-digit AGS.',
        "",
        f"Source: Destatis Gemeindeverzeichnis, {title}",
        "Generated by generate_gemeinden_nrw.py",
        '"""',
        "",
        "gemeinden_nrw = {",
    ]
    for ags, name in sorted(gemeinden.items()):
        kreis, kreisfrei = kreise[ags[:5]]
        lines.append(
            f'    "{ags}": {{"name": "{name}", "kreis": "{kreis}", "kreisfrei": {kreisfrei}}},'
        )
    lines.append("}")
    OUT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(f"Written {len(gemeinden)} municipalities in {len(kreise)} districts to {OUT_PATH}")


if __name__ == "__main__":
    main()
